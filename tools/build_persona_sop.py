def load_engine_keys():
    """把 parameters.toml 展平为 set of 'section.key' 与 'section.sub.key'，用于校验 eng 引用。"""
    d = tomllib.loads(PARAMS.read_text(encoding="utf-8"))
    keys = set()

    def walk(node, path):
        for k, v in node.items():
            p = f"{path}.{k}" if path else k
            if isinstance(v, dict):
                keys.add(p)      # 中间节点（section）本身也视为合法引用
                walk(v, p)
            else:
                keys.add(p)

    walk(d, "")
    return d, keys


SRC_V = re.compile(r"v(\d{1,2})(?:@(\d{2}):(\d{2}))?")
SRC_DATE = re.compile(r"\b(\d{4}-\d{2}-\d{2})\b")


def resolve_src(src, videos_by_v, videos_by_date):
    """把 src 解析成结构化出处列表。"""
    out = []
    for m in SRC_V.finditer(src):
        v = int(m.group(1))
        e = videos_by_v.get(str(v))
        if e:
            rec = dict(kind="video", v=v, date=e["date"], title=e["title"],
                       dur_s=e["duration_s"], t=m.group(0))
            if m.group(2) and int(m.group(2)) * 60 + int(m.group(3)) > e["duration_s"]:
                rec["oob"] = True
            out.append(rec)
    for m in SRC_DATE.finditer(src):
        d = m.group(1)
        e = videos_by_date.get(d)
        rec = dict(kind="date", date=d)
        if e:
            rec["title"] = e["title"]
            rec["dur_s"] = e["duration_s"]
        out.append(rec)
    if not out:  # 形如 "2026-09-11" 之外的裸期号汇总
        out.append(dict(kind="raw", raw=src))
    return out


